"""Área de trabalho: barra (dock), painéis do CRM, ERP e Lumos, páginas como janelas, alternar, fechar e favoritos."""
import asyncio
from playwright.async_api import async_playwright
exec(open('tests/navegador/base_menu_real.py').read().split("async def main():")[0])
async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch(executable_path=__import__("os").environ.get("LUMOS_CHROMIUM") or None)
    ctx = await b.new_context(viewport={"width": 1366, "height": 860}, service_workers="block")
    await ctx.add_init_script("localStorage.setItem('lumos:modo-demo','cliente')")
    pg = await ctx.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)[:140]))
    async def route(r):
      name = r.request.url.split("/js/")[-1].split("?")[0]
      if name in STUBS: await r.fulfill(body=STUBS[name], content_type="application/javascript")
      else: await r.continue_()
    await pg.route("**/js/*.js*", route)
    ok = lambda c, m: print(("ok: " if c else "FALHOU: ") + m)
    await pg.goto("http://localhost:8765/inicio.html"); await pg.wait_for_selector("body.ad-pronta")
    ok(await pg.locator(".ad-dock-grupo").count() == 3, "barra com Lumos, CRM e ERP")
    ok(await pg.locator("#ad-area [data-fav]").count() == 0 and await pg.locator(".ad-dica").count() == 0, "área de trabalho começa vazia e sem aviso")
    await pg.screenshot(path="tests/saida/area1.png")
    await pg.click('[data-grupo="crm"]'); await pg.wait_for_timeout(250)
    nomes = await pg.eval_on_selector_all("#ad-grade [data-abrir] > span:not(.ad-tile)", "e=>e.map(x=>x.textContent)")
    ok("Dashboard" in nomes and "Kanban" in nomes, "painel do CRM com Dashboard e Kanban: " + ", ".join(nomes))
    await pg.screenshot(path="tests/saida/area2.png")
    await pg.click('#ad-grade [data-abrir="kanban"]'); await pg.wait_for_timeout(1500)
    f = pg.frame_locator('.ad-janela[data-key="kanban"] iframe')
    ok(await pg.locator(".ad-janela.ativa").count() == 1, "Kanban abriu como janela")
    ok(await f.locator("html.em-janela").count() == 1 and not await f.locator(".dash-side").is_visible(), "dentro da janela a página não mostra o menu lateral")
    await pg.click('[data-grupo="erp"]'); await pg.wait_for_timeout(200)
    await pg.fill("#ad-busca", "pdv"); await pg.wait_for_timeout(100)
    await pg.click('#ad-grade [data-abrir="pdv"]'); await pg.wait_for_timeout(1200)
    ok(await pg.locator(".ad-dock-app").count() == 2 and await pg.locator('.ad-dock-app.ativa[data-janela="pdv"]').count() == 1, "duas páginas abertas na barra, PDV na frente")
    await pg.screenshot(path="tests/saida/area3.png")
    await pg.click('.ad-dock-app[data-janela="kanban"]'); await pg.wait_for_timeout(200)
    ok(await pg.locator('.ad-janela.ativa[data-key="kanban"]').count() == 1, "clicar no Kanban da barra volta para ele sem recarregar")
    await pg.click('.ad-dock-app[data-janela="kanban"]'); await pg.wait_for_timeout(200)
    ok(await pg.locator(".ad-janela.ativa").count() == 0, "clicar de novo minimiza e mostra a área de trabalho")
    await pg.hover('.ad-dock-app[data-janela="pdv"]'); await pg.click('[data-fechar="pdv"]'); await pg.wait_for_timeout(200)
    ok(await pg.locator(".ad-dock-app").count() == 1, "fechar o PDV tira ele da barra")
    # fixa Kanban e PDV pelo alfinete do painel
    await pg.click('[data-grupo="crm"]'); await pg.hover('#ad-grade [data-abrir="kanban"]'); await pg.click('[data-fixar="kanban"]')
    await pg.click('[data-grupo="erp"]'); await pg.hover('#ad-grade [data-abrir="pdv"]'); await pg.click('[data-fixar="pdv"]'); await pg.keyboard.press("Escape")
    ok(await pg.locator("#ad-area [data-fav]").count() == 2, "alfinete fixa os atalhos na área de trabalho")
    await pg.click('#ad-area [data-fav="pdv"]'); await pg.wait_for_timeout(1000)
    ok(await pg.locator('.ad-janela.ativa[data-key="pdv"]').count() == 1, "um clique no atalho abre a página na frente")
    await pg.click('.ad-dock-app[data-janela="pdv"]'); await pg.wait_for_timeout(200)
    await pg.dblclick('#ad-area [data-fav="pdv"]'); await pg.wait_for_timeout(600)
    ok(await pg.locator('.ad-janela.ativa[data-key="pdv"]').count() == 1, "clique duplo no atalho também abre a página na frente")
    await pg.click('.ad-dock-app[data-janela="pdv"]'); await pg.wait_for_timeout(200)
    ic = pg.locator('#ad-area [data-fav="kanban"]'); bx = await ic.bounding_box()
    await pg.mouse.move(bx["x"] + 40, bx["y"] + 30); await pg.mouse.down(); await pg.mouse.move(bx["x"] + 300, bx["y"] + 40, steps=8); await pg.mouse.up(); await pg.wait_for_timeout(300)
    nb = await ic.bounding_box(); ok(nb["x"] > bx["x"] + 150, "arrastar o favorito muda o lugar dele")
    ok(await pg.locator('.ad-janela.ativa').count() == 0, "arrastar não abre a página")
    salvo = await pg.evaluate("Object.keys(localStorage).some(k=>k.startsWith('lumos:area:'))"); ok(salvo, "posição dos favoritos guardada")
    await pg.click('[data-grupo="lumos"]'); await pg.wait_for_timeout(200)
    ok(await pg.locator("#ad-sair").count() == 1 and await pg.locator("#ad-tema").count() == 1, "painel Lumos com modo escuro e Sair")
    lumos = await pg.eval_on_selector_all("#ad-grade [data-abrir] > span:not(.ad-tile)", "e=>e.map(x=>x.textContent)")
    ok("Configurações" in lumos and "Equipe" in lumos, "painel Lumos com Configurações e Equipe: " + ", ".join(lumos))
    await pg.screenshot(path="tests/saida/area4.png")
    m = await ctx.new_page(); await m.set_viewport_size({"width": 390, "height": 844}); await m.route("**/js/*.js*", route)
    await m.goto("http://localhost:8765/inicio.html"); await m.wait_for_selector("body.ad-pronta"); await m.click('[data-grupo="erp"]'); await m.wait_for_timeout(300)
    await m.screenshot(path="tests/saida/area5.png")
    print("ERROS", errs); await b.close()
asyncio.run(main())
